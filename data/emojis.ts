const RECENT_EMOJIS_KEY = 'vee_recent_emojis_v1';

export const getRecentEmojis = (): string[] => {
  try {
    const saved = localStorage.getItem(RECENT_EMOJIS_KEY);
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (e) {
    console.error('Failed to load recent emojis', e);
  }
  return ['🔥', '✨', '❤️', '😂', '🚀', '💯', '🥳', '😱', '👍', '🎉'];
};

export const addRecentEmoji = (emojiStr: string): void => {
  try {
    const recents = getRecentEmojis();
    const filtered = recents.filter((e) => e !== emojiStr);
    const updated = [emojiStr, ...filtered].slice(0, 24);
    localStorage.setItem(RECENT_EMOJIS_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to save recent emoji', e);
  }
};
